create schema bk_first_1000_private;
revoke all on schema bk_first_1000_private from public, anon, authenticated;

create table bk_first_1000_private.cohort (
  singleton boolean primary key default true check (singleton),
  reserved integer not null check (reserved between 0 and 1000)
);

create table public.ball_knower_first_1000_badges (
  user_id uuid primary key references auth.users(id) on delete cascade,
  spot integer not null unique check (spot between 1 and 1000),
  claimed_at timestamptz
);

alter table public.ball_knower_first_1000_badges enable row level security;
revoke all on public.ball_knower_first_1000_badges from public, anon, authenticated;
grant select (user_id, claimed_at) on public.ball_knower_first_1000_badges to authenticated;

create policy bk_first_1000_read on public.ball_knower_first_1000_badges
  for select to authenticated using (
    (select auth.uid()) is not null
    and not coalesce((select auth.jwt()->>'is_anonymous') = 'true', false)
    and (
      user_id = (select auth.uid())
      or (claimed_at is not null and public.ball_knower_can_see_sender(user_id))
    )
  );

-- Close the gap between taking the signup snapshot and installing the trigger.
lock table auth.users in share row exclusive mode;

with earliest as (
  select id, row_number() over (order by created_at, id) as spot
  from auth.users
  where is_anonymous is not true and confirmed_at is not null
  order by created_at, id
  limit 1000
)
insert into public.ball_knower_first_1000_badges (user_id, spot)
select id, spot from earliest;

insert into bk_first_1000_private.cohort (reserved)
select count(*) from public.ball_knower_first_1000_badges;

create function bk_first_1000_private.reserve_spot()
returns trigger
language plpgsql security definer set search_path = '' as $$
declare next_spot integer;
begin
  if new.is_anonymous is true or new.confirmed_at is null then
    return new;
  end if;
  if tg_op = 'UPDATE' then
    if old.is_anonymous is not true and old.confirmed_at is not null then
      return new;
    end if;
  end if;
  if exists (select 1 from public.ball_knower_first_1000_badges where user_id = new.id) then
    return new;
  end if;

  -- This row serializes concurrent enrollments and never recycles a deleted spot.
  update bk_first_1000_private.cohort
  set reserved = reserved + 1
  where singleton and reserved < 1000
  returning reserved into next_spot;

  if next_spot is not null then
    insert into public.ball_knower_first_1000_badges (user_id, spot)
    values (new.id, next_spot);
  end if;
  return new;
end;
$$;

revoke all on function bk_first_1000_private.reserve_spot() from public, anon, authenticated;

-- confirmed_at is generated by Supabase Auth from its email/phone confirmation fields.
create trigger bk_first_1000_reserve
after insert or update of is_anonymous, email_confirmed_at, phone_confirmed_at on auth.users
for each row execute function bk_first_1000_private.reserve_spot();

create function bk_first_1000_private.claim(p_user_id uuid)
returns boolean
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null or auth.uid() is distinct from p_user_id
     or coalesce(auth.jwt()->>'is_anonymous' = 'true', false) then
    return false;
  end if;

  update public.ball_knower_first_1000_badges
  set claimed_at = now()
  where user_id = p_user_id and claimed_at is null;

  return exists (
    select 1 from public.ball_knower_first_1000_badges
    where user_id = p_user_id and claimed_at is not null
  );
end;
$$;

revoke all on function bk_first_1000_private.claim(uuid) from public, anon, authenticated;
grant usage on schema bk_first_1000_private to authenticated;
grant execute on function bk_first_1000_private.claim(uuid) to authenticated;

create function public.bk_claim_first_1000_badge(p_user_id uuid)
returns boolean
language sql security invoker set search_path = '' as $$
  select bk_first_1000_private.claim(p_user_id);
$$;

revoke all on function public.bk_claim_first_1000_badge(uuid) from public, anon, authenticated;
grant execute on function public.bk_claim_first_1000_badge(uuid) to authenticated;
