import assert from 'node:assert/strict';
import {dressMyAthlete} from '../athleteWardrobe';
import {DEFAULT_OUTFIT,saveOutfit,readOutfit,setVerifiedWardrobe} from '../playerWardrobe';
import {withAthleteIdentity} from '../athletePassport';
const storage=new Map<string,string>();
Object.assign(globalThis,{localStorage:{getItem:(key:string)=>storage.get(key)??null,setItem:(key:string,value:string)=>storage.set(key,value)},window:{dispatchEvent(){}}});
const base={id:'competitive-seed-1',name:'Fixed athlete',position:'WR',speed:85,agility:85,acceleration:85,careerStrength:85,contact:85};
const identity={id:'my-career',name:'Elijah',number:21};
const outfit={...DEFAULT_OUTFIT,top:'top-forest',shorts:'shorts-slate',shoes:'shoes-white',wrist:'wrist-white'};
saveOutfit(outfit);
const player=dressMyAthlete(withAthleteIdentity(base,identity),'workout');
assert.deepEqual(player.wardrobe,outfit);assert.equal(player.name,'Elijah');
for(const key of ['id','position','speed','agility','acceleration','careerStrength','contact'])assert.equal(player[key],base[key],'Cosmetics cannot change competitive state');
assert.equal(Object.hasOwn(base,'wardrobe'),false,'NPC/shared template stays untouched');
const game=dressMyAthlete(player,'game');assert.equal(Object.hasOwn(game,'wardrobe'),false);assert.deepEqual(readOutfit(),outfit,'Entering a game cannot overwrite saved clothes');
assert.deepEqual(dressMyAthlete(game,'workout').wardrobe,outfit,'Leaving game restores personal outfit');
saveOutfit({...outfit,top:'top-gold'});assert.equal(dressMyAthlete(base,'workout').wardrobe?.top,'top-standard','Forged local premium item stays locked');
setVerifiedWardrobe({owned:['top-gold'],outfit:{...outfit,top:'top-gold'}});assert.equal(dressMyAthlete(base,'workout').wardrobe?.top,'top-gold');
setVerifiedWardrobe(null);assert.equal(dressMyAthlete(base,'workout').wardrobe?.top,'top-standard','Account reset removes premium clothes');
console.log('PASS outfit persistence across workout/game/workout, fixed competitive identity/stats, NPC isolation and verified-only premium gear.');
