import assert from 'node:assert/strict';
import {flightTelemetry,runnerTelemetry} from '../public/play-moment-3d/tracker.js';
import {fieldAlignedFrame,newBallCameraRecovery,recoverBallCamera,isBallOccluded} from '../public/play-moment-3d/camera.js';
import {nearFootballHotZones} from '../public/play-moment-3d/ui.js';
const throwData={from:[0,1.5,20],to:[13,1.7,48],duration:.6,t:0,arc:3};
const start=flightTelemetry(throwData);assert(start&&start.groundSpeed>0&&start.gravity>0);
assert(start.predicted[2]>start.position[2]);
const end=flightTelemetry({...throwData,t:1});assert.equal(end.position[0],13);assert.equal(end.position[2],48);
assert.equal(end.seconds,0);
assert.equal(flightTelemetry({...throwData,duration:0}),null);
assert.equal(flightTelemetry({...throwData,from:[NaN,1,2]}),null);
const runner=runnerTelemetry({x:10,z:95,vx:3,vz:8});assert(runner.groundSpeed>8);
assert.equal(runnerTelemetry({x:0,z:0,vx:0,vz:0}),null);
const frame=fieldAlignedFrame({eye:[40,8,140],target:[29,1,124]});
assert.equal(frame.target[0],26.3);assert.equal(frame.target[2],110);assert(frame.snapped);
assert(isBallOccluded([0,2,0],[0,1,10],[{x:0,z:5}]));
assert(!isBallOccluded([0,2,0],[0,1,10],[{x:5,z:5}]));
const recovery=newBallCameraRecovery(),view={eye:[0,8,5],target:[0,1,20]},ball=flightTelemetry(throwData);
const size={width:800,height:350};
for(let i=0;i<60;i++)recoverBallCamera(recovery,view,ball,{visible:true,x:400,y:175},size,1/60);
assert.equal(recovery.fade,0);assert.equal(recovery.lost,0);
let adjusted=view;
for(let i=0;i<50;i++)adjusted=recoverBallCamera(recovery,adjusted,ball,{visible:false,x:-100,y:175},size,1/60);
assert(adjusted.target[2]>view.target[2]);assert(recovery.fade>0&&recovery.fade<=.18);
assert(nearFootballHotZones([24,1,104]).some(zone=>zone.type==='corner'));
assert.deepEqual(nearFootballHotZones([0,1,45]),[]);
console.log('Ball telemetry, field bounds, occlusion recovery, and football hot-zone checks passed.');
