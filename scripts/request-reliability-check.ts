import assert from 'node:assert/strict';
import { createResilientFetch } from '../resilientFetch';

let calls = 0;
const policy = { readTimeoutMs: 15, writeTimeoutMs: 15, readAttempts: 3, retryDelayMs: 0 };
const transient = createResilientFetch({ ...policy, fetch: (async () => new Response(++calls < 3 ? 'down' : '{"ok":true}', { status: calls < 3 ? 503 : 200 })) as typeof fetch });
assert.deepEqual(await (await transient('https://example.invalid/read')).json(), { ok: true });
assert.equal(calls, 3);
calls = 0;
await transient(new Request('https://example.invalid/write', { method: 'POST', body: 'one action' }));
assert.equal(calls, 1, 'Request-object mutations must never be mistaken for retryable GETs');
calls = 0;
const stalled = createResilientFetch({ ...policy, fetch: (async () => { calls++; return new Promise(() => {}); }) as typeof fetch });
await assert.rejects(stalled('https://example.invalid/write', { method: 'POST' }), { name: 'AbortError' });
assert.equal(calls, 1, 'An uncooperative native mutation has a deadline and no automatic replay');
calls = 0;
await assert.rejects(stalled('https://example.invalid/read'), { name: 'AbortError' });
assert.equal(calls, 3, 'Reads retry a bounded number of times even when abort is ignored');
const controller = new AbortController();
controller.abort(); calls = 0;
await assert.rejects(stalled('https://example.invalid/read', { signal: controller.signal }), { name: 'AbortError' });
assert.equal(calls, 0, 'A cancelled caller must not dispatch a request');
calls = 0;
const activeAbort = new AbortController();
const aborted = stalled(new Request('https://example.invalid/read', { signal: activeAbort.signal }));
activeAbort.abort();
await assert.rejects(aborted, { name: 'AbortError' });
assert.equal(calls, 1, 'Request signals are retained and cancellation is not retried');
const stalledBody = createResilientFetch({ ...policy, readAttempts: 1, fetch: (async () => new Response(new ReadableStream({ start() {} }))) as typeof fetch });
await assert.rejects(stalledBody('https://example.invalid/read'), { name: 'AbortError' }, 'Headers without a completed body cannot hang cloud recovery');
let finishOld: (response: Response) => void;
const committed: string[] = [];
const ordered = createResilientFetch({ ...policy, fetch: (async (_url, init) => {
  const value = String(init?.body);
  if (value === 'old') return new Promise<Response>(resolve => { finishOld = response => { committed.push(value); resolve(response); }; });
  committed.push(value); return new Response('{}');
}) as typeof fetch });
await assert.rejects(ordered('https://example.invalid/state?select=value', { method: 'POST', body: 'old' }), { name: 'AbortError' });
await assert.rejects(ordered('https://example.invalid/state', { method: 'POST', body: 'new' }), { name: 'AbortError' });
assert.deepEqual(committed, [], 'A timed-out native write cannot be overtaken by its provider retry');
finishOld!(new Response('{}')); await new Promise(resolve => setImmediate(resolve));
await ordered('https://example.invalid/state', { method: 'POST', body: 'new' });
assert.deepEqual(committed, ['old', 'new']);
console.log('PASS bounded API reads/bodies, native abort fallback, mutation method detection, cancellation and no mutation replay.');
