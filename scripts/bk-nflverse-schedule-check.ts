import assert from 'node:assert/strict';
import { normalizeNflverseSchedule, getNflverseGames, NFLVERSE_SCHEDULE_URL, easternKickoff } from '../api/bk/v1/games';
import { resetNflverseCache } from '../server/bk/nflverse-csv';
const header = 'game_id,season,week,gameday,gametime,away_team,home_team,away_score,home_score\n';
const csv = header + '2026_01_DAL_PHI,2026,1,2026-09-10,20:20,DAL,PHI,17,24\n2026_02_KC_BUF,2026,2,2026-09-20,13:00,KC,BUF,,\n2025_01_DAL_PHI,2025,1,2025-09-10,20:20,DAL,PHI,1,2\n';
const games = normalizeNflverseSchedule(csv);
assert.equal(games.length, 2);
assert.equal(games[0].home, 'PHI');
assert.equal(games[0].homeScore, 24);
assert.equal(games[0].status, 'final');
assert.equal(games[1].homeScore, null);
assert.equal(games[1].status, 'scheduled');
assert.equal(games[1].startTime, '2026-09-20T17:00:00.000Z');
assert.equal(easternKickoff('2026-12-20', '13:00'), '2026-12-20T18:00:00.000Z');
assert.equal(easternKickoff('2026-02-30', '13:00'), null);
assert.equal(easternKickoff('2026-09-20', 'TBD'), null);
assert.equal(NFLVERSE_SCHEDULE_URL, 'https://github.com/nflverse/nflverse-data/releases/download/schedules/games.csv');
const teams = 'ARI ATL BAL BUF CAR CHI CIN CLE DAL DEN DET GB HOU IND JAX KC LAC LAR LV MIA MIN NE NO NYG NYJ PHI PIT SEA SF TB TEN WAS'.split(' ');
const rows = header + Array.from({ length: 272 }, (_, i) => {
  const week = Math.floor(i / 16) + 1, away = teams[(i * 2) % 32], home = teams[(i * 2 + 1) % 32];
  return `2026_${String(week).padStart(2, '0')}_${away}_${home},2026,${week},2026-10-01,13:00,${away},${home},,`;
}).join('\n');
resetNflverseCache();
let calls = 0;
const data = await getNflverseGames(async () => { calls++; return new Response(rows); }, () => Date.parse('2026-10-31T10:00:00Z'));
assert.equal(data.items.length, 272);
const cached = await getNflverseGames(async () => { throw new Error('cache missed'); }, () => Date.parse('2026-10-31T10:01:00Z'));
assert.equal(cached.updatedAt, data.updatedAt);
assert.equal(calls, 1);
resetNflverseCache();
await assert.rejects(getNflverseGames(async () => new Response(csv)), /incomplete_schedule/);
console.log('nflverse schedule adapter contract checks passed');
