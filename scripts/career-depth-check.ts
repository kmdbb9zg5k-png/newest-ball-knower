import assert from 'node:assert/strict';
import { advanceFranchiseInteractionSeason, createFranchiseInteractions, ensureFranchiseWeek, franchiseWeeklyBriefing, respondToFranchiseScenario, resolveFranchiseWeek, syncFranchiseInteractions } from '../franchiseInteractions';
import { counterGmTradeOffer, emptyGmTradeInbox, generateGmTradeOffer, gmTradeCounterOptions, gmTradeRosterPreview, restoreGmTradeInbox, validateGmTradeOffer } from '../gmTradeOffers';
import { buildSoloTeamRoster } from '../soloFranchiseEngine';
import { SOLO_TEAM_THEMES } from '../soloUniverse';
import { agentDealForSeason, canNegotiateAgentDeal, evaluateAgentCounter, normalizeAgentDeal } from '../agentContractNegotiation';
import { createClientCareer } from '../agentClientCareer';
import { createCareerArc, finishArcSeason } from '../myPlayerArc';
import { createCareerLife, cleanCareerLife } from '../myPlayerCareer';
import { ownerFinancialOutlook } from '../OwnerFinancialBrief';
import { advanceOwnerSeason, ownerSeasonCalendar } from '../ownerSeasonEngine';

const roster = buildSoloTeamRoster(SOLO_TEAM_THEMES[0].abbr);
let state = createFranchiseInteractions(roster);
const playerId = state.pendingScenario!.playerId;
const initial = syncFranchiseInteractions(state, roster).relationships![playerId];
state = respondToFranchiseScenario(state, 'commit', roster);
const promised = state;
assert.equal(respondToFranchiseScenario(state, 'commit', roster), state, 'A meeting cannot award trust or promises twice');
state = resolveFranchiseWeek(state, roster, [], 1, [], false).state;
assert.equal(state.relationships![playerId].promisesBroken, 1);
assert(state.relationships![playerId].trust < initial.trust);
assert.deepEqual(resolveFranchiseWeek(state, roster, [], 1, [], false).state, state, 'A completed week must not resolve promises twice');
state = ensureFranchiseWeek(state, roster, 2);
assert.equal(state.pendingScenario?.kind, 'trust_repair');
assert.equal(state.pendingScenario?.playerId, playerId);
assert.match(state.pendingScenario!.relatedTo!, /Missed promise/);
state = respondToFranchiseScenario(state, 'honest', roster);
const trust = state.relationships![playerId].trust;
assert.equal(state.relationships![playerId].promisesBroken, 1, 'Owning a failure does not erase the record');
const restored = syncFranchiseInteractions(JSON.parse(JSON.stringify(state)), roster);
assert.equal(restored.relationships![playerId].trust, trust);
const nextYear = advanceFranchiseInteractionSeason(restored, roster, 2027);
assert.equal(nextYear.relationships![playerId].trust, trust);
assert.equal(nextYear.relationships![playerId].promisesBroken, 1);
assert.equal(nextYear.season, 2027);
assert.equal(nextYear.decisions.length, 0);
assert(nextYear.pendingScenario);
assert.equal(franchiseWeeklyBriefing(nextYear, roster).relationships.length, roster.length);
const legacy = { ...state, relationships: undefined, followUps: undefined, resolvedWeeks: undefined };
assert.equal(syncFranchiseInteractions(legacy, roster).development[playerId].morale, state.development[playerId].morale);
const injuryState = ensureFranchiseWeek(resolveFranchiseWeek({ ...promised, promises: [] }, roster, [], 1, [{ playerId, playerName: roster.find(p => p.id === playerId)!.name, position: 'QB', weeks: 2, week: 1, severity: 'Moderate' }], false).state, roster, 2);
assert.equal(injuryState.pendingScenario?.kind, 'recovery');
assert.equal(injuryState.pendingScenario?.playerId, playerId);
const league = Object.fromEntries(SOLO_TEAM_THEMES.map(team => [team.abbr, buildSoloTeamRoster(team.abbr)]));
let counterCount = 0;
for (const team of SOLO_TEAM_THEMES) for (const week of [3, 6, 9]) {
  const roster = league[team.abbr];
  const offer = generateGmTradeOffer(team.abbr, roster, league, week, 2026, false, []);
  assert(offer, `${team.abbr} week ${week} must receive a legal call`);
  const inbox = { ...emptyGmTradeInbox(), pending: offer };
  const counters = gmTradeCounterOptions(offer, team.abbr, roster, league, week, 2026, false);
  for (const counter of counters) {
    counterCount++;
    const result = validateGmTradeOffer(counter, team.abbr, roster, league, week, 2026, false);
    assert.deepEqual(result.errors, []);
    assert(gmTradeRosterPreview(roster, result.userRoster).capRoom >= -.001);
    const revised = counterGmTradeOffer(inbox, counter);
    assert.equal(revised.pending?.id, counter.id);
    assert.equal(revised.decisions[0].status, 'countered');
    assert.deepEqual(restoreGmTradeInbox(JSON.parse(JSON.stringify(revised)), team.abbr), revised);
    assert.equal(generateGmTradeOffer(team.abbr, roster, league, week, 2026, false, revised.decisions), null, 'The original call cannot return');
    assert.deepEqual(counterGmTradeOffer(revised, counter), revised, 'Double counter taps must be idempotent');
    assert.equal(gmTradeCounterOptions(counter, team.abbr, roster, league, week, 2026, false).length, 0);
  }
}
assert(counterCount > 0, 'The league must support real counter variations');
const career = createClientCareer([]), player = roster[0], agency = { negotiation: 30, reputation: 20 };
const expensive = { annualM: 26, years: 5, guaranteedPct: 80, gmPatience: 70, strategy: 'maximize_aav' as const };
const evaluation = evaluateAgentCounter(expensive, 20, player, career, agency);
assert.equal(evaluation.accepted, false, 'A high request cannot auto-succeed in later rounds');
assert(evaluation.nextPatience < expensive.gmPatience);
assert.equal(evaluation.totalM, 130);
assert.equal(evaluation.guaranteedM, 104);
assert.equal(evaluation.feeK, 3900);
assert(evaluateAgentCounter({ ...expensive, years: 2, annualM: 16, guaranteedPct: 40 }, 20, player, career, agency).accepted);
const deal = normalizeAgentDeal({ annualM: 10, totalM: 30, guaranteedM: 15, years: 3, negotiatedAt: '2026-09-03', signingYear: 2026 }, 2026)!;
assert.equal(deal.startYear, 2027); assert.equal(deal.endYear, 2029);
assert.equal(canNegotiateAgentDeal(deal, 2026), false);
assert.equal(canNegotiateAgentDeal(deal, 2028), false);
assert.equal(canNegotiateAgentDeal(deal, 2029), true);
assert.deepEqual(normalizeAgentDeal(JSON.parse(JSON.stringify(deal)), 2029), deal);
assert.equal(normalizeAgentDeal({ ...deal, years: NaN }, 2026), undefined);
const renewalClient = { playerId: player.id, futureDeal: deal };
assert.equal(agentDealForSeason(renewalClient, [], 2029)?.annualM, 10);
const renewed = normalizeAgentDeal({ ...deal, annualM: 15, totalM: 45, signingYear: 2029, startYear: 2030, playerId: player.id }, 2029)!;
const preserved = { ...renewalClient, activeDeal: agentDealForSeason(renewalClient, [], 2029), futureDeal: renewed };
assert.equal(agentDealForSeason(preserved, [], 2029)?.annualM, 10, 'Renewing must preserve the current-year salary');
assert.equal(agentDealForSeason(JSON.parse(JSON.stringify(preserved)), [], 2029)?.endYear, 2029, 'Current deal must survive a save/reload');
assert.equal(agentDealForSeason(preserved, [], 2030)?.annualM, 15, 'The new salary begins in its own start year');
assert.equal(agentDealForSeason({ playerId: player.id, futureDeal: renewed }, [{ ...deal, playerId: player.id }], 2029)?.annualM, 10, 'Identified history can recover an active contract');
assert.equal(agentDealForSeason({ playerId: player.id, futureDeal: renewed }, [{ ...deal, playerId: 'someone-else' }], 2029), undefined, 'Another client cannot supply the current salary');
const inferred = normalizeAgentDeal({ annualM: 10, totalM: 30, guaranteedM: 15, years: 3, negotiatedAt: '2026-09-03' }, 2029)!;
assert.equal(inferred.inferredTiming, true, 'Legacy timing must be marked inferred');
assert.equal(normalizeAgentDeal(inferred, 2030)?.startYear, inferred.startYear, 'Inferred terms cannot slide on subsequent restores');
assert.equal(normalizeAgentDeal({ ...deal, signingYear: undefined }, 2040)?.signingYear, 2026, 'An explicit start year is a reliable anchor');
const ownerBase = { abbr: SOLO_TEAM_THEMES[0].abbr, season: 2026, stage: 'regular' as const, week: 1, wins: 0, losses: 0, cashM: 350, ticketPrice: 125, parkingPrice: 35, fanTrust: 55, stadium: 72, playoffSeed: 0, seasonRevenueM: 20, seasonExpensesM: 5, seasonStaffCommitmentsM: 17.5 };
const homeWeek = ownerSeasonCalendar(ownerBase.abbr, 2026).find(week => week.isHome)!;
const awayWeek = ownerSeasonCalendar(ownerBase.abbr, 2026).find(week => !week.isHome && !week.isBye)!;
const homeFinancials = ownerFinancialOutlook({ ...ownerBase, week: homeWeek.week });
assert.equal(homeFinancials.netM, 15);
assert.equal(homeFinancials.cashAfterCommitmentsM, 332.5);
assert(homeFinancials.gateM > 0);
assert.equal(ownerFinancialOutlook({ ...ownerBase, week: awayWeek.week }).gateM, 0);
const close = advanceOwnerSeason({ ...ownerBase, stage: 'super-bowl', week: 21, gmCostM: 17.5, coachCostM: 0 }, true);
assert.equal(close.expensesM, 17.5);
assert.equal(close.revenueM, 85);
assert.equal(close.profitM, 67.5);
assert(close.seasonEnded);
const profile = { name: 'Career depth', position: 'QB' as const, teamAbbr: SOLO_TEAM_THEMES[0].abbr, draftRound: 2, draftPick: 1, overall: 78 };
const life = createCareerLife(profile);
const arc = createCareerArc(profile);
const next = finishArcSeason(arc, life, profile, 2026, 10, false)!;
assert.equal(next.arc.seasons[0].team, profile.teamAbbr);
assert.equal(next.arc.seasons[0].role, life.role);
assert.equal(next.arc.seasons[0].overall, 78);
assert.equal(next.arc.seasons[0].annual, arc.contract.annual);
assert(cleanCareerLife(JSON.parse(JSON.stringify(life)), profile));
console.log(`PASS career depth: durable trust/failure/recovery follow-ups, migration and season rollover, idempotent decisions, ${counterCount} legal counter variants across 32 clubs/3 calls, repeat contract windows/terms/fees, Owner home/away gate and annual settlement, MyPlayer season context.`);
