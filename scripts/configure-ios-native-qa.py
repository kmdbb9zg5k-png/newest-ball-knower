#!/usr/bin/env python3
"""Add an unsigned fixture-only UI test target for system URL-open consent."""

import hashlib
import importlib.util
import plistlib
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path


def identifier(name):
    return hashlib.sha1(("ball-knower-native-qa:" + name).encode()).hexdigest()[:24].upper()


def add_ui_test_target(project):
    objects = project["objects"]
    root = objects[project["rootObject"]]
    app_id = next(key for key, value in objects.items() if value.get("isa") == "PBXNativeTarget" and value.get("name") == "App")
    target_id, product_id, file_id, group_id = [identifier(name) for name in ["target", "product", "source", "group"]]
    source_build_id, sources_id, frameworks_id, resources_id, configs_id = [identifier(name) for name in ["source-build", "sources", "frameworks", "resources", "configs"]]
    proxy_id, dependency_id = identifier("app-proxy"), identifier("app-dependency")
    objects[file_id] = {"isa": "PBXFileReference", "lastKnownFileType": "sourcecode.swift", "path": "NativeURLConsentTests.swift", "sourceTree": "<group>"}
    objects[group_id] = {"isa": "PBXGroup", "children": [file_id], "path": "NativeUITests", "sourceTree": "<group>"}
    objects[product_id] = {"isa": "PBXFileReference", "explicitFileType": "wrapper.cfbundle", "includeInIndex": 0, "path": "NativeUITests.xctest", "sourceTree": "BUILT_PRODUCTS_DIR"}
    objects[source_build_id] = {"isa": "PBXBuildFile", "fileRef": file_id}
    for phase_id, kind, files in [(sources_id, "PBXSourcesBuildPhase", [source_build_id]), (frameworks_id, "PBXFrameworksBuildPhase", []), (resources_id, "PBXResourcesBuildPhase", [])]:
        objects[phase_id] = {"isa": kind, "buildActionMask": 2147483647, "files": files, "runOnlyForDeploymentPostprocessing": 0}
    objects[proxy_id] = {"isa": "PBXContainerItemProxy", "containerPortal": project["rootObject"], "proxyType": 1, "remoteGlobalIDString": app_id, "remoteInfo": "App"}
    objects[dependency_id] = {"isa": "PBXTargetDependency", "target": app_id, "targetProxy": proxy_id}
    configuration_ids = []
    for name in ["Debug", "Release"]:
        config_id = identifier("config-" + name)
        configuration_ids.append(config_id)
        settings = {
            "CODE_SIGN_STYLE": "Automatic", "GENERATE_INFOPLIST_FILE": "YES", "CURRENT_PROJECT_VERSION": "1",
            "IPHONEOS_DEPLOYMENT_TARGET": "16.4", "LD_RUNPATH_SEARCH_PATHS": ["$(inherited)", "@executable_path/Frameworks", "@loader_path/Frameworks"],
            "MARKETING_VERSION": "1.0", "PRODUCT_BUNDLE_IDENTIFIER": "com.ballknower.ios.nativeqa.uitests",
            "PRODUCT_NAME": "$(TARGET_NAME)", "SWIFT_VERSION": "5.0", "TARGETED_DEVICE_FAMILY": "1,2", "TEST_TARGET_NAME": "App",
        }
        if name == "Debug":
            settings.update({"SWIFT_OPTIMIZATION_LEVEL": "-Onone", "SWIFT_ACTIVE_COMPILATION_CONDITIONS": "DEBUG $(inherited)"})
        objects[config_id] = {"isa": "XCBuildConfiguration", "buildSettings": settings, "name": name}
    objects[configs_id] = {"isa": "XCConfigurationList", "buildConfigurations": configuration_ids, "defaultConfigurationIsVisible": 0, "defaultConfigurationName": "Release"}
    objects[target_id] = {
        "isa": "PBXNativeTarget", "buildConfigurationList": configs_id,
        "buildPhases": [sources_id, frameworks_id, resources_id], "buildRules": [], "dependencies": [dependency_id],
        "name": "NativeUITests", "productName": "NativeUITests", "productReference": product_id,
        "productType": "com.apple.product-type.bundle.ui-testing",
    }
    for collection, value in [(root["targets"], target_id), (objects[root["mainGroup"]]["children"], group_id), (objects[root["productRefGroup"]]["children"], product_id)]:
        if value not in collection:
            collection.append(value)
    root.setdefault("attributes", {}).setdefault("TargetAttributes", {})[target_id] = {"CreatedOnToolsVersion": "26.6", "TestTargetID": app_id}
    return target_id


def configure_scheme(path, target_id, app_id):
    if path.exists():
        tree = ET.parse(path)
        scheme = tree.getroot()
    else:
        # The locked Capacitor template relies on Xcode's autogenerated App
        # scheme. Make an explicit equivalent only for this UI-test fixture.
        scheme = ET.Element("Scheme", {"LastUpgradeVersion": "2660", "version": "1.3"})
        tree = ET.ElementTree(scheme)
        app_reference = {"BuildableIdentifier": "primary", "BlueprintIdentifier": app_id, "BuildableName": "App.app", "BlueprintName": "App", "ReferencedContainer": "container:App.xcodeproj"}
        action = ET.SubElement(scheme, "BuildAction", {"parallelizeBuildables": "YES", "buildImplicitDependencies": "YES"})
        entries = ET.SubElement(action, "BuildActionEntries")
        entry = ET.SubElement(entries, "BuildActionEntry", {"buildForTesting": "YES", "buildForRunning": "YES", "buildForProfiling": "YES", "buildForArchiving": "YES", "buildForAnalyzing": "YES"})
        ET.SubElement(entry, "BuildableReference", app_reference)
        debugger = {"selectedDebuggerIdentifier": "Xcode.DebuggerFoundation.Debugger.LLDB", "selectedLauncherIdentifier": "Xcode.IDEFoundation.Launcher.LLDB"}
        ET.SubElement(scheme, "TestAction", {"buildConfiguration": "Debug", "shouldUseLaunchSchemeArgsEnv": "YES", **debugger})
        launch = ET.SubElement(scheme, "LaunchAction", {"buildConfiguration": "Debug", "launchStyle": "0", "useCustomWorkingDirectory": "NO", "ignoresPersistentStateOnLaunch": "NO", "debugDocumentVersioning": "YES", "debugServiceExtension": "internal", "allowLocationSimulation": "YES", **debugger})
        ET.SubElement(ET.SubElement(launch, "BuildableProductRunnable", {"runnableDebuggingMode": "0"}), "BuildableReference", app_reference)
        profile = ET.SubElement(scheme, "ProfileAction", {"buildConfiguration": "Release", "shouldUseLaunchSchemeArgsEnv": "YES", "savedToolIdentifier": "", "useCustomWorkingDirectory": "NO", "debugDocumentVersioning": "YES"})
        ET.SubElement(ET.SubElement(profile, "BuildableProductRunnable", {"runnableDebuggingMode": "0"}), "BuildableReference", app_reference)
        ET.SubElement(scheme, "AnalyzeAction", {"buildConfiguration": "Debug"})
        ET.SubElement(scheme, "ArchiveAction", {"buildConfiguration": "Release", "revealArchiveInOrganizer": "YES"})
    reference = {"BuildableIdentifier": "primary", "BlueprintIdentifier": target_id, "BuildableName": "NativeUITests.xctest", "BlueprintName": "NativeUITests", "ReferencedContainer": "container:App.xcodeproj"}
    entries = scheme.find("BuildAction/BuildActionEntries")
    assert entries is not None, "The generated App build action is missing"
    if not any(item.get("BlueprintIdentifier") == target_id for item in entries.iter("BuildableReference")):
        entry = ET.SubElement(entries, "BuildActionEntry", {"buildForTesting": "YES", "buildForRunning": "NO", "buildForProfiling": "NO", "buildForArchiving": "NO", "buildForAnalyzing": "YES"})
        ET.SubElement(entry, "BuildableReference", reference)
    action = scheme.find("TestAction")
    assert action is not None, "The generated App test action is missing"
    testables = action.find("Testables")
    if testables is None:
        testables = ET.SubElement(action, "Testables")
    if not any(item.get("BlueprintIdentifier") == target_id for item in testables.iter("BuildableReference")):
        testable = ET.SubElement(testables, "TestableReference", {"skipped": "NO", "parallelizable": "NO"})
        ET.SubElement(testable, "BuildableReference", reference)
    ET.indent(tree, space="   ")
    path.parent.mkdir(parents=True, exist_ok=True)
    tree.write(path, encoding="UTF-8", xml_declaration=True)


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    spec = importlib.util.spec_from_file_location("configure_ios", Path(__file__).with_name("configure-ios-project.py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    project_path = root / "ios/App/App.xcodeproj/project.pbxproj"
    project = module.configure_project(module.read_project(project_path), qa=True)
    target_id = add_ui_test_target(project)
    project_path.write_bytes(plistlib.dumps(project, sort_keys=False))
    app_id = next(key for key, value in project["objects"].items() if value.get("isa") == "PBXNativeTarget" and value.get("name") == "App")
    configure_scheme(root / "ios/App/App.xcodeproj/xcshareddata/xcschemes/App.xcscheme", target_id, app_id)
    destination = root / "ios/App/NativeUITests"
    destination.mkdir(exist_ok=True)
    shutil.copyfile(root / "scripts/fixtures/NativeURLConsentTests.swift", destination / "NativeURLConsentTests.swift")
    print("Added the fixture-only native UI test target for normal system URL-open consent.")
