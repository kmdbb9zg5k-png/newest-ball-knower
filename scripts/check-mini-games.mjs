import assert from 'node:assert/strict';
import { MINI_LEVELS, miniGameFromSearch, miniRatings, miniInitialDrive, miniSession, miniSnap, miniWhistle, miniBetweenPlays, miniTimeout, miniSpike, miniFinish, saveMiniBest } from '../public/play-moment-3d/mini-games.js';
assert.equal(miniGameFromSearch('?difficulty=all-pro'), null);
assert.equal(miniGameFromSearch('?mode=two-minute&difficulty=bad').level.id, 'rookie');
const ratings = { speed: 90, acceleration: 90, coverage: 88, blockShed: 80, tackle: 85, awareness: 80 };
const levels = MINI_LEVELS.map(level => miniRatings(ratings, 1, level));
assert(levels[0].coverage < levels[1].coverage && levels[1].coverage < levels[2].coverage);
assert(levels.every(level => level.speed === 90 && level.acceleration === 90));
assert.equal(miniRatings(ratings, 0, MINI_LEVELS[2]), ratings);
assert(MINI_LEVELS[0].readScale > MINI_LEVELS[1].readScale && MINI_LEVELS[1].readScale > MINI_LEVELS[2].readScale);
const s = miniSession(), d = miniInitialDrive();
miniBetweenPlays(s, d, 'pre', 60); assert.equal(d.clock, 120);
miniSnap(s); d.clock -= 4; d.ball += 6;
miniWhistle(s, d, 'TACKLED', 6);
miniBetweenPlays(s, d, 'dead', 3); assert.equal(d.clock, 113);
miniBetweenPlays(s, d, 'pre', 5); assert.equal(d.clock, 108);
assert.equal(miniTimeout(s, d, 'run'), false);
assert.equal(miniTimeout(s, d, 'pre'), true); assert.equal(s.timeouts, 2);
assert.equal(miniTimeout(s, d, 'pre'), false);
miniBetweenPlays(s, d, 'pre', 10); assert.equal(d.clock, 108);
miniSnap(s); miniWhistle(s, d, 'OUT OF BOUNDS', 3);
miniBetweenPlays(s, d, 'dead', 3); assert.equal(d.clock, 108);
miniSnap(s); miniWhistle(s, d, 'PASS BROKEN UP', 0, true);
miniBetweenPlays(s, d, 'pre', 5); assert.equal(d.clock, 108);
assert.equal(miniSpike(s, d, 'run'), false);
assert.equal(miniSpike(s, d, 'pre'), true); assert.equal(d.clock, 107); assert.equal(d.down, 2);
const spot = d.ball, target = d.ball + d.toGo;
assert.equal(miniBetweenPlays(s, d, 'pre', 40), 'DELAY OF GAME');
assert.equal(d.ball, spot - 5); assert.equal(d.ball + d.toGo, target); assert.equal(d.down, 2);
for (let i = 0; i < 2; i++) { miniSnap(s); assert(miniTimeout(s, d, 'pre')); }
miniSnap(s); assert.equal(miniTimeout(s, d, 'pre'), false); assert.equal(s.timeouts, 0);
d.clock = .1; assert.equal(miniBetweenPlays(s, d, 'pre', .2), 'TIME EXPIRED');
const loss = miniFinish(s, d, 'TIME EXPIRED'); assert.equal(loss.won, false);
assert.equal(miniFinish(s, d, 'TOUCHDOWN'), loss);
assert.equal(miniSpike(s, d, 'pre'), false);
const winSession = miniSession(), winDrive = { ...miniInitialDrive(), ball: 100, clock: 0, score: 29, plays: 8 };
const win = miniFinish(winSession, winDrive, 'TOUCHDOWN'); assert.equal(win.won, true);
const data = new Map(), storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
saveMiniBest(storage, 'rookie', { ...win, remaining: 45 });
assert.equal(saveMiniBest(storage, 'rookie', { ...win, remaining: 20 }), 45);
assert.equal(saveMiniBest(storage, 'all-pro', { ...win, remaining: 12 }), 12);
assert.equal(saveMiniBest(storage, 'rookie', loss), null);
assert.equal(saveMiniBest({getItem(){throw Error('denied')}}, 'rookie', win), null);
console.log('PASS: level effects, unchanged speed/offense, in-bounds clock, stopped clock, timeouts, spike, delay penalty, outcomes, and per-level records.');
