export function getOfficialMaddenRating(playerId: string, defaultName?: string, defaultTeam?: string, defaultPos?: Position): {
  playerId: string;
  fullName: string;
  team: string;
  position: Position;
  overallRating: number;
  ratingSource: "EA SPORTS Madden";
  ratingSeason: number;
  lastUpdated: string;
  ratingStatus: "VERIFIED" | "RATING_REVIEW_REQUIRED";
  previousOvr?: number;
  legacyRatingRemoved?: boolean;
  notes?: string;
} {
  const match = OFFICIAL_MADDEN_RATINGS[playerId];
  if (match) {
    return {
      playerId: match.playerId,
      fullName: match.fullName,
      team: match.team,
      position: match.position,
      overallRating: match.overallRating,
      ratingSource: "EA SPORTS Madden",
      ratingSeason: 2026,
      lastUpdated: match.lastUpdated,
      ratingStatus: match.status,
      previousOvr: match.previousOvr,
      legacyRatingRemoved: !!match.previousOvr && match.previousOvr !== match.overallRating,
      notes: match.notes,
    };
  }

  return {
    playerId,
    fullName: defaultName || "Unknown Player",
    team: defaultTeam || "FA",
    position: defaultPos || "QB",
    overallRating: 75,
    ratingSource: "EA SPORTS Madden",
    ratingSeason: 2026,
    lastUpdated: MADDEN_RATING_METADATA.lastUpdated,
    ratingStatus: "RATING_REVIEW_REQUIRED",
    notes: "Rating review required for " + (defaultName || playerId),
  };
}
