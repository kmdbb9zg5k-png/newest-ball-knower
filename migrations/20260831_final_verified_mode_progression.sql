-- Final Phase 4B: server-authoritative Owner progression, authenticated Agent
-- transition verification, and server-verified Prediction picks.
-- Clients never choose progression event types, XP awards, rating deltas, or
-- idempotency keys.

create schema if not exists ball_knower_private;

-- Remove the abandoned counter-snapshot prototype if this migration is replayed
-- on a development database that saw an earlier draft.
drop function if exists public.record_ball_knower_verified_mode_snapshot(uuid,text,jsonb);
drop table if exists ball_knower_private.verified_mode_state;

create table if not exists ball_knower_private.verified_mode_milestones (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('owner','agent','prediction')),
  milestone_type text not null check (milestone_type in (
    'owner_season_complete','owner_playoff_appearance','owner_conference_title','owner_championship',
    'agent_client_signed','agent_trade_resolved','agent_contract_signed','agent_promise_fulfilled',
    'prediction_correct','prediction_wrong','prediction_push'
  )),
  source_key text not null,
  payload jsonb not null default '{}'::jsonb,
  verified_at timestamptz not null default now(),
  verified_by text not null default 'server',
  claimed_at timestamptz,
  unique(user_id,mode,source_key)
);
create index if not exists verified_mode_milestones_unclaimed_idx
  on ball_knower_private.verified_mode_milestones(user_id,verified_at)
  where claimed_at is null;
alter table ball_knower_private.verified_mode_milestones enable row level security;
revoke all on table ball_knower_private.verified_mode_milestones from public,anon,authenticated;

-- Owner mode uses a private, versioned server run. The browser can ask to
-- advance a matching run, but it cannot choose the result or postseason path.
create table if not exists ball_knower_private.verified_owner_runs (
  user_id uuid primary key references auth.users(id) on delete cascade,
  abbr text not null,
  season integer not null check (season between 2026 and 2200),
  week integer not null check (week between 0 and 21),
  stage text not null check (stage in ('preseason','regular','wild-card','divisional','conference','super-bowl')),
  wins integer not null default 0 check (wins between 0 and 20),
  losses integer not null default 0 check (losses between 0 and 20),
  playoff_seed integer check (playoff_seed is null or playoff_seed between 1 and 7),
  version integer not null default 1 check (version > 0),
  updated_at timestamptz not null default now()
);
alter table ball_knower_private.verified_owner_runs enable row level security;
revoke all on table ball_knower_private.verified_owner_runs from public,anon,authenticated;

-- Agent mode is still a local solo career, but rewards are derived from exact
-- authenticated OLD -> NEW cloud-state transitions rather than browser counters.
-- This lifecycle table makes client replays/removals idempotent.
create table if not exists ball_knower_private.verified_agent_clients (
  user_id uuid not null references auth.users(id) on delete cascade,
  player_id text not null,
  legacy_baseline boolean not null default true,
  signed_at timestamptz not null default now(),
  last_contract_season integer,
  last_trade_season integer,
  fulfilled_promises text[] not null default '{}'::text[],
  primary key(user_id,player_id)
);
alter table ball_knower_private.verified_agent_clients enable row level security;
revoke all on table ball_knower_private.verified_agent_clients from public,anon,authenticated;

