as $$
  select case when auth.role()='service_role' then (
    select to_jsonb(r) from ball_knower_private.verified_owner_runs r where r.user_id=p_user_id
  ) else null end;
$$;
revoke all on function public.get_ball_knower_verified_owner_run(uuid) from public,anon,authenticated;
grant execute on function public.get_ball_knower_verified_owner_run(uuid) to service_role;

create or replace function public.begin_ball_knower_verified_owner_run(
  p_user_id uuid,p_abbr text,p_season integer
) returns jsonb
language plpgsql
security definer
set search_path=public,ball_knower_private,pg_temp
as $$
declare v_run ball_knower_private.verified_owner_runs%rowtype;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required'; end if;
  if p_user_id is null or p_abbr !~ '^[A-Z]{2,3}$' or p_season<2026 or p_season>2200 then
    raise exception 'Invalid Owner run';
  end if;
  select * into v_run from ball_knower_private.verified_owner_runs where user_id=p_user_id for update;
  if not found then
    insert into ball_knower_private.verified_owner_runs(user_id,abbr,season,week,stage,wins,losses,playoff_seed,version)
    values(p_user_id,p_abbr,p_season,0,'preseason',0,0,null,1)
    returning * into v_run;
  elsif p_season>v_run.season then
    update ball_knower_private.verified_owner_runs
    set abbr=p_abbr,season=p_season,week=0,stage='preseason',wins=0,losses=0,playoff_seed=null,version=version+1,updated_at=now()
    where user_id=p_user_id returning * into v_run;
  end if;
  return to_jsonb(v_run);
end;
$$;
