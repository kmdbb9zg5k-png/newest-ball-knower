grant execute on function public.begin_ball_knower_verified_owner_run(uuid,text,integer) to service_role;

create or replace function public.commit_ball_knower_verified_owner_step(
  p_user_id uuid,
  p_expected_version integer,
  p_next_season integer,
  p_next_week integer,
  p_next_stage text,
  p_next_wins integer,
  p_next_losses integer,
  p_next_playoff_seed integer,
  p_won boolean
) returns jsonb
language plpgsql
security definer
set search_path=public,ball_knower_private,pg_temp
as $$
declare
  v_old ball_knower_private.verified_owner_runs%rowtype;
  v_new ball_knower_private.verified_owner_runs%rowtype;
  v_ids jsonb:='[]'::jsonb;
  v_id bigint;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required'; end if;
  select * into v_old from ball_knower_private.verified_owner_runs
  where user_id=p_user_id for update;
  if not found then raise exception 'Verified Owner run not found'; end if;
  if v_old.version<>p_expected_version then raise exception 'Verified Owner run changed'; end if;
  if p_next_stage not in ('preseason','regular','wild-card','divisional','conference','super-bowl')
     or p_next_season<v_old.season or p_next_season>v_old.season+1
     or p_next_week<0 or p_next_week>21
     or p_next_wins<0 or p_next_wins>20 or p_next_losses<0 or p_next_losses>20
     or (p_next_playoff_seed is not null and (p_next_playoff_seed<1 or p_next_playoff_seed>7)) then
    raise exception 'Invalid verified Owner transition';
  end if;

  if v_old.stage='regular' and v_old.week=18 and p_next_stage in ('wild-card','divisional') then
    v_id:=ball_knower_private.insert_verified_mode_milestone(
      p_user_id,'owner','owner_playoff_appearance','owner:'||v_old.season||':playoffs',
      jsonb_build_object('season',v_old.season),'owner_server_run_v1'
    );
    v_ids:=v_ids||jsonb_build_array(v_id);
  end if;
  if v_old.stage='conference' and p_next_stage='super-bowl' and p_won then
    v_id:=ball_knower_private.insert_verified_mode_milestone(
      p_user_id,'owner','owner_conference_title','owner:'||v_old.season||':conference',
      jsonb_build_object('season',v_old.season),'owner_server_run_v1'
    );
    v_ids:=v_ids||jsonb_build_array(v_id);
  end if;
  if v_old.stage='super-bowl' and p_next_stage='preseason' and p_next_season=v_old.season+1 and p_won then
    v_id:=ball_knower_private.insert_verified_mode_milestone(
      p_user_id,'owner','owner_championship','owner:'||v_old.season||':championship',
      jsonb_build_object('season',v_old.season),'owner_server_run_v1'
    );
    v_ids:=v_ids||jsonb_build_array(v_id);
  end if;
  if p_next_stage='preseason' and p_next_season=v_old.season+1 then
    v_id:=ball_knower_private.insert_verified_mode_milestone(
      p_user_id,'owner','owner_season_complete','owner:'||v_old.season||':complete',
      jsonb_build_object('season',v_old.season,'champion',v_old.stage='super-bowl' and p_won),'owner_server_run_v1'
    );
    v_ids:=v_ids||jsonb_build_array(v_id);
  end if;

  update ball_knower_private.verified_owner_runs
  set season=p_next_season,week=p_next_week,stage=p_next_stage,wins=p_next_wins,losses=p_next_losses,
      playoff_seed=p_next_playoff_seed,version=version+1,updated_at=now()
  where user_id=p_user_id
  returning * into v_new;
  return jsonb_build_object('run',to_jsonb(v_new),'milestoneIds',v_ids);
end;
$$;
revoke all on function public.commit_ball_knower_verified_owner_step(uuid,integer,integer,integer,text,integer,integer,integer,boolean) from public,anon,authenticated;
grant execute on function public.commit_ball_knower_verified_owner_step(uuid,integer,integer,integer,text,integer,integer,integer,boolean) to service_role;

-- Safely decode the Agent cloud envelope. Bad JSON never blocks cloud sync.
create or replace function ball_knower_private.agent_state_doc(p_value jsonb)
returns jsonb
language plpgsql
immutable
set search_path=pg_catalog,pg_temp
as $$
declare v_doc jsonb;
begin
  if p_value is null or jsonb_typeof(p_value)<>'object' or not (p_value ? 'raw') then return null; end if;
  begin v_doc:=(p_value->>'raw')::jsonb; exception when others then return null; end;
  if jsonb_typeof(v_doc)<>'object' then return null; end if;
  return v_doc;
end;
$$;
revoke all on function ball_knower_private.agent_state_doc(jsonb) from public,anon,authenticated;

create or replace function ball_knower_private.agent_state_int(p_doc jsonb,p_key text,p_max integer)
returns integer
language plpgsql
immutable
set search_path=pg_catalog,pg_temp
as $$
declare v text; n integer;
begin
  if p_doc is null then return -1; end if;
  v:=p_doc->>p_key;
  if v is null or v!~'^\d+$' then return -1; end if;
  n:=v::integer;
  if n<0 or n>p_max then return -1; end if;
  return n;
end;
$$;
revoke all on function ball_knower_private.agent_state_int(jsonb,text,integer) from public,anon,authenticated;

create or replace function ball_knower_private.verify_agent_state_transition()
returns trigger
language plpgsql
security definer
set search_path=public,ball_knower_private,pg_temp
as $$
declare
  v_old jsonb;
  v_new jsonb;
  v_old_clients jsonb;
  v_new_clients jsonb;
  v_old_client jsonb;
  v_new_client jsonb;
  v_pid text;
  v_season integer;
  v_old_week integer;
  v_new_week integer;
  v_old_actions integer;
  v_new_actions integer;
  v_old_signed integer;
  v_new_signed integer;
  v_added integer:=0;
  v_inserted text;
  v_promise text;
  v_promises text[];
  v_lifecycle ball_knower_private.verified_agent_clients%rowtype;
  v_deal jsonb;
  v_old_deals integer;
  v_new_deals integer;
  v_id bigint;
begin
  if new.state_key<>'player_agent_career' then return new; end if;
  v_new:=ball_knower_private.agent_state_doc(new.value);
  if v_new is null then return new; end if;
  v_new_clients:=case when jsonb_typeof(v_new->'clients')='array' then v_new->'clients' else '[]'::jsonb end;

  if tg_op='INSERT' then
    v_season:=ball_knower_private.agent_state_int(v_new,'seasonYear',2200);
    for v_new_client in select value from jsonb_array_elements(v_new_clients) loop
      v_pid:=nullif(btrim(v_new_client->>'playerId'),'');
      if v_pid is null then continue; end if;
      v_promises:=array(select jsonb_array_elements_text(
        case when jsonb_typeof(v_new_client#>'{career,fulfilledPromises}')='array' then v_new_client#>'{career,fulfilledPromises}' else '[]'::jsonb end
      ));
      insert into ball_knower_private.verified_agent_clients(
        user_id,player_id,legacy_baseline,last_contract_season,last_trade_season,fulfilled_promises
      ) values(
        new.user_id,v_pid,true,
        case when jsonb_typeof(v_new_client->'futureDeal')='object' then nullif(v_season,-1) else null end,
        case when v_new_client#>>'{tradeRequest,status}'='resolved' then nullif(v_season,-1) else null end,
        coalesce(v_promises,'{}'::text[])
      ) on conflict(user_id,player_id) do nothing;
    end loop;
    return new;
  end if;

  v_old:=ball_knower_private.agent_state_doc(old.value);
  if v_old is null then return new; end if;
  v_old_clients:=case when jsonb_typeof(v_old->'clients')='array' then v_old->'clients' else '[]'::jsonb end;
  v_season:=ball_knower_private.agent_state_int(v_new,'seasonYear',2200);

  -- Everything present before this authenticated transition is baseline history.
  for v_old_client in select value from jsonb_array_elements(v_old_clients) loop
    v_pid:=nullif(btrim(v_old_client->>'playerId'),'');
    if v_pid is null then continue; end if;
    v_promises:=array(select jsonb_array_elements_text(
      case when jsonb_typeof(v_old_client#>'{career,fulfilledPromises}')='array' then v_old_client#>'{career,fulfilledPromises}' else '[]'::jsonb end
    ));
    insert into ball_knower_private.verified_agent_clients(
      user_id,player_id,legacy_baseline,last_contract_season,last_trade_season,fulfilled_promises
    ) values(
      new.user_id,v_pid,true,
      case when jsonb_typeof(v_old_client->'futureDeal')='object' then nullif(ball_knower_private.agent_state_int(v_old,'seasonYear',2200),-1) else null end,
      case when v_old_client#>>'{tradeRequest,status}'='resolved' then nullif(ball_knower_private.agent_state_int(v_old,'seasonYear',2200),-1) else null end,
      coalesce(v_promises,'{}'::text[])
    ) on conflict(user_id,player_id) do nothing;
  end loop;

  -- A signing must add exactly one detailed client in the same Agent week,
  -- consume exactly one of the two weekly actions, and increment signedClients.
  select count(*) into v_added
  from jsonb_array_elements(v_new_clients) n
  where nullif(btrim(n->>'playerId'),'') is not null
    and not exists (
      select 1 from jsonb_array_elements(v_old_clients) o where o->>'playerId'=n->>'playerId'
    );
  v_old_actions:=ball_knower_private.agent_state_int(v_old,'weeklyActionsUsed',2);
  v_new_actions:=ball_knower_private.agent_state_int(v_new,'weeklyActionsUsed',2);
  v_old_signed:=ball_knower_private.agent_state_int(v_old,'signedClients',10000);
  v_new_signed:=ball_knower_private.agent_state_int(v_new,'signedClients',10000);
  v_old_week:=ball_knower_private.agent_state_int(v_old,'seasonWeek',30);
  v_new_week:=ball_knower_private.agent_state_int(v_new,'seasonWeek',30);

  if v_added=1
     and v_old_signed>=0 and v_new_signed=v_old_signed+1
     and v_old_actions>=0 and v_new_actions=v_old_actions+1
     and v_old->>'seasonYear'=v_new->>'seasonYear'
     and v_old->>'phase'=v_new->>'phase'
     and v_old_week=v_new_week
     and jsonb_array_length(v_new_clients)=jsonb_array_length(v_old_clients)+1
     and jsonb_array_length(v_new_clients)<=5 then
    select value into v_new_client
    from jsonb_array_elements(v_new_clients) n
    where not exists(select 1 from jsonb_array_elements(v_old_clients) o where o->>'playerId'=n->>'playerId')
    limit 1;
    v_pid:=nullif(btrim(v_new_client->>'playerId'),'');
    if v_pid is not null
       and jsonb_typeof(v_new_client#>'{career,promises}')='array'
       and jsonb_array_length(v_new_client#>'{career,promises}')=2
       and nullif(btrim(v_new_client->>'signedAt'),'') is not null then
      insert into ball_knower_private.verified_agent_clients(user_id,player_id,legacy_baseline)
      values(new.user_id,v_pid,false)
      on conflict(user_id,player_id) do nothing
      returning player_id into v_inserted;
      if v_inserted is not null then
        perform ball_knower_private.insert_verified_mode_milestone(
          new.user_id,'agent','agent_client_signed','agent:client:'||v_pid,
          jsonb_build_object('playerId',v_pid,'season',v_season),'agent_cloud_transition_v1'
        );
      end if;
    end if;
  end if;

  v_old_deals:=case when jsonb_typeof(v_old->'dealHistory')='array' then jsonb_array_length(v_old->'dealHistory') else 0 end;
  v_new_deals:=case when jsonb_typeof(v_new->'dealHistory')='array' then jsonb_array_length(v_new->'dealHistory') else 0 end;
  v_deal:=case when v_new_deals=v_old_deals+1 then v_new->'dealHistory'->(v_new_deals-1) else null end;

  -- Compare each persistent client for concrete contract/trade/promise transitions.
  for v_new_client in select value from jsonb_array_elements(v_new_clients) loop
    v_pid:=nullif(btrim(v_new_client->>'playerId'),'');
    if v_pid is null then continue; end if;
    select value into v_old_client from jsonb_array_elements(v_old_clients)
    where value->>'playerId'=v_pid limit 1;
    if v_old_client is null then continue; end if;
    select * into v_lifecycle from ball_knower_private.verified_agent_clients
    where user_id=new.user_id and player_id=v_pid for update;
    if not found then continue; end if;

    if v_season>=2026 and v_new_deals=v_old_deals+1
       and jsonb_typeof(v_deal)='object'
       and jsonb_typeof(v_new_client->'futureDeal')='object'
       and v_new_client->'futureDeal'=v_deal
       and v_old_client->'futureDeal' is distinct from v_new_client->'futureDeal'
       and jsonb_typeof(v_deal->'totalM')='number'
       and jsonb_typeof(v_deal->'annualM')='number'
       and jsonb_typeof(v_deal->'guaranteedM')='number'
       and jsonb_typeof(v_deal->'years')='number'
       and (v_deal->>'totalM')::numeric between 1 and 1000
       and (v_deal->>'annualM')::numeric between 0.1 and 150
       and (v_deal->>'guaranteedM')::numeric between 0 and 1000
       and (v_deal->>'years')::numeric between 1 and 10
       and v_lifecycle.last_contract_season is distinct from v_season then
      update ball_knower_private.verified_agent_clients
      set last_contract_season=v_season where user_id=new.user_id and player_id=v_pid;
      perform ball_knower_private.insert_verified_mode_milestone(
        new.user_id,'agent','agent_contract_signed','agent:contract:'||v_pid||':'||v_season,
        jsonb_build_object('playerId',v_pid,'season',v_season),'agent_cloud_transition_v1'
      );
    end if;

    if v_season>=2026
       and v_new->>'phase'='regular'
       and v_new_week between 1 and 9
       and v_old_client#>>'{tradeRequest,status}'='open'
       and v_new_client#>>'{tradeRequest,status}'='resolved'
       and nullif(btrim(v_new_client#>>'{tradeRequest,destination}'),'') is not null
       and v_lifecycle.last_trade_season is distinct from v_season then
      update ball_knower_private.verified_agent_clients
      set last_trade_season=v_season where user_id=new.user_id and player_id=v_pid;
      perform ball_knower_private.insert_verified_mode_milestone(
        new.user_id,'agent','agent_trade_resolved','agent:trade:'||v_pid||':'||v_season,
        jsonb_build_object('playerId',v_pid,'season',v_season),'agent_cloud_transition_v1'
      );
    end if;

    if jsonb_typeof(v_new_client#>'{career,fulfilledPromises}')='array' then
      for v_promise in
        select jsonb_array_elements_text(v_new_client#>'{career,fulfilledPromises}')
        except
        select jsonb_array_elements_text(
          case when jsonb_typeof(v_old_client#>'{career,fulfilledPromises}')='array'
               then v_old_client#>'{career,fulfilledPromises}' else '[]'::jsonb end
        )
      loop
        if v_promise in ('money','guarantees','loyalty','winning','playing_time','family','brand','long_term')
           and not (v_promise=any(v_lifecycle.fulfilled_promises)) then
          update ball_knower_private.verified_agent_clients
          set fulfilled_promises=array_append(fulfilled_promises,v_promise)
          where user_id=new.user_id and player_id=v_pid;
          perform ball_knower_private.insert_verified_mode_milestone(
            new.user_id,'agent','agent_promise_fulfilled','agent:promise:'||v_pid||':'||v_promise,
            jsonb_build_object('playerId',v_pid,'promise',v_promise),'agent_cloud_transition_v1'
          );
        end if;
      end loop;
    end if;
  end loop;

  return new;
exception when others then
  -- Progression verification must never make the user's cloud save unavailable.
  raise warning 'Agent progression verification skipped: %',sqlerrm;
  return new;
end;
$$;
revoke all on function ball_knower_private.verify_agent_state_transition() from public,anon,authenticated;

